namespace Display13PanelTiming {
constexpr uintptr_t Query=0x49D46,Selection=0x49EAA;
constexpr uint8_t Before[] {0xBB,0x0F,0x00,0x00,0x00};
constexpr uint8_t After[] {0x90,0x90,0x90,0x90,0x90};
// Preflight the pipe load, conditional legacy override, M/N reads/stores and
// division together. Keeping EBX retains path+3640, not a hard-coded pipe A.
constexpr uint8_t Entry[] {0x55,0x48,0x89,0xE5,0x41,0x57,0x41,0x56,0x41,0x55,0x41,0x54,0x53};
constexpr uint8_t Select[] {
    0x41,0x8B,0x9C,0x24,0x40,0x36,0x00,0x00,0x48,0xFF,0x05,0x51,0x48,0x09,0x00,
    0x4D,0x85,0xC0,0x74,0x23,0x48,0xFF,0x05,0x55,0x48,0x09,0x00,0x48,0xFF,0xC1,
    0x48,0x89,0x0D,0x73,0x4A,0x09,0x00,0x83,0x78,0x08,0x00,0x75,0x0C,
    0x48,0xFF,0x05,0x36,0x48,0x09,0x00,0xBB,0x0F,0x00,0x00,0x00,0xC1,0xE3,0x0C};
constexpr uint8_t Reads[] {
    0x49,0x8B,0xBE,0x40,0x0C,0x00,0x00,0x8D,0xB3,0x40,0x00,0x06,0x00,
    0xE8,0x80,0x44,0x01,0x00,0x41,0x89,0x84,0x24,0x60,0x01,0x00,0x00,
    0x49,0x8B,0xBE,0x40,0x0C,0x00,0x00,0x81,0xC3,0x44,0x00,0x06,0x00,
    0x48,0x89,0xDE,0xE8,0x63,0x44,0x01,0x00,0x41,0x89,0x84,0x24,0x64,0x01,0x00,0x00};
constexpr uint8_t Divide[] {
    0x41,0x8B,0x84,0x24,0x60,0x01,0x00,0x00,0x41,0x8B,0x8C,0x24,0x64,0x01,0x00,0x00,
    0x48,0x0F,0xAF,0xC3,0x31,0xD2,0x48,0xF7,0xF1};
struct Guard {uintptr_t offset;const uint8_t *bytes;size_t length;};
constexpr Guard Guards[] {
    {Query,Entry,sizeof(Entry)}, {0x49E78,Select,sizeof(Select)},
    {0x49EB2,Reads,sizeof(Reads)}, {0x4A00B,Divide,sizeof(Divide)}
};
enum class Plan {NotRequired,Rejected,Ready};
inline Plan plan(bool panel,const void *image,size_t size,uintptr_t queryOffset) {
    if(!panel)return Plan::NotRequired;
    if(!image || queryOffset!=Query)return Plan::Rejected;
    const auto data=static_cast<const uint8_t *>(image);
    for(const auto &g:Guards)
        if(g.offset>size || g.length>size-g.offset || memcmp(data+g.offset,g.bytes,g.length))return Plan::Rejected;
    return Plan::Ready;
}
}
